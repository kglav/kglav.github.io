-- Household chore checklist tables.
-- This does NOT alter calendar_entries, recurring_tasks, games, or game_platforms.

create table if not exists public.chore_tasks (
  id text primary key,
  title text not null,
  cadence text not null check (cadence in ('daily','weekly','monthly','optional','one_off')),
  description text,
  timing text,
  target_completion text,
  condition_text text,
  assigned_to text,
  sort_order integer not null default 100,
  active boolean not null default true,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists public.chore_completions (
  id bigint generated by default as identity primary key,
  task_id text not null references public.chore_tasks(id) on delete cascade,
  period_key text not null,
  completed_by text not null,
  completed_at timestamptz not null default now(),
  unique(task_id, period_key)
);

alter table public.chore_tasks enable row level security;
alter table public.chore_completions enable row level security;

grant select, insert, update, delete on public.chore_tasks to anon, authenticated;
grant select, insert, update, delete on public.chore_completions to anon, authenticated;
grant usage, select on sequence public.chore_completions_id_seq to anon, authenticated;

drop policy if exists "chore_tasks_read" on public.chore_tasks;
drop policy if exists "chore_tasks_write" on public.chore_tasks;
drop policy if exists "chore_completions_read" on public.chore_completions;
drop policy if exists "chore_completions_write" on public.chore_completions;

create policy "chore_tasks_read" on public.chore_tasks for select to anon, authenticated using (true);
create policy "chore_tasks_write" on public.chore_tasks for all to anon, authenticated using (true) with check (true);
create policy "chore_completions_read" on public.chore_completions for select to anon, authenticated using (true);
create policy "chore_completions_write" on public.chore_completions for all to anon, authenticated using (true) with check (true);

